package com.example.dto;

import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class UserRequestDTO {

    @Schema(description = "Nombre completo", example = "Carlos Ruiz")
    @NotBlank(message = "El nombre es obligatorio")
    @Size(max = 100, message = "El nombre no puede tener mas de 100 caracteres")
    private String name;

    @Schema(description = "Correo, debe ser unico", example = "carlos@finanzas.com")
    @NotBlank(message = "El correo es obligatorio")
    @Email(message = "El correo no tiene un formato valido")
    @Size(max = 120, message = "El correo no puede tener mas de 120 caracteres")
    private String email;

    @Schema(description = "Contraseña, obligatoria al crear y opcional al actualizar", example = "clave123")
    @Size(min = 6, message = "La contraseña debe tener al menos 6 caracteres")
    private String password;

    @Schema(description = "Id del rol del usuario", example = "2")
    @NotNull(message = "El rol es obligatorio")
    private Long roleId;
    // Id must be generated by us

}
